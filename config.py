#   τ の振幅が足りない            1.077 倍
#   透過率が実測より低い（0.65 vs 0.68）1.046 倍
#   ────────────────────────────────
#   積                            1.127 倍
# 実際に使っていた 1.20 は、これより 6% 行きすぎていた。
#
# 【直し方】
# 原因のところを直した。τ を実測から当てはめ直し（第2-2節）、
# 透過率を実測値かつ季節変化つきにした（第4-1節）。
# これで一律の係数は要らなくなり、月ごとのばらつきは
