# --- 5-2. 光応答曲線の形 ---
#
# 【なぜ式の形を替えるのか】
# 光合成.xlsx の光応答は直角双曲線 f(I) = I/(I+KL) で、演習用としては
# これで十分だが、実物のトマトの光応答曲線は再現できない。
#
# 直角双曲線は飽和の立ち上がりが緩すぎて、
#   ・初期勾配（量子収率）を文献に合わせると、飽和値が足りない
#   ・飽和値を合わせると、初期勾配が立ちすぎる
# という板挟みになる。実際、文献値2つ（量子収率0.06・飽和光での純光合成
# 24 μmol/m²/s）を同時に満たす KL と Pmax を数値的に解くと、
# KL=332 W/m²（半飽和 PPFD 1519）・Pmax=151.6 μmol/m²/s という、
# 実在の葉の3倍という値に飛ぶ。パラメータでは直らない。
#
# 【非直角双曲線】
#   P = [ φI + Pmax − √((φI + Pmax)² − 4θ·φI·Pmax) ] / (2θ)
#
#   φ  : 量子収率。弱光での傾き。
#   Pmax: 光飽和したときの総光合成速度。
#   θ  : 曲率。0 に近いほど緩やかに、1 に近いほど角ばって飽和する。
#
# θ が初期勾配と飽和点を切り離すので、両方を同時に満たせる。
# 葉の光合成ではこちらが標準形。
