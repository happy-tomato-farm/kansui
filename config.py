#
# 【入れる日射予測はハウス内センサー値そのもの】（2026-09-17 ユーザー確認）
# 1日に何回かに分けて潅水するとき、「この後さらに出すべきか」を
# その時点の日射で判断する。その場で読めるのはハウス内センサーだけなので、
# センサー値をそのまま入れる仕様にしてある。
# ÷0.65 と ×film はレシピ側が内部でやっているので、こちらで掛けてはいけない。
#
# 【したがって守るべき約束】
#   ・分母は「実質日射」＝ センサー値 ÷ RECIPE_RADIATION_COEF × フィルム係数
#   ・RECIPE_RADIATION_COEF とフィルム係数は、レシピ側の coef・film と同じ値にする
#
# ずれると潅水量がそのままの比率でずれる。たとえば中央ハウスで
# こちらが film=1.00、レシピ側が film=0.95 のままだと、
# 実際に出る水が 5% 少なくなる。
#
# ★★ ここが最も誤解しやすいので、はっきり書いておく ★★
#
# RECIPE_RADIATION_COEF は物理量ではない。ただの単位の取り決めである。
#
# 「実質日射」はハウス外の日射の推定値のように見えるが、そうではない。
# 実測の透過率は季節で 0.62〜0.72 と動くので（第4-1節）、
# 固定値 0.65 で割った値が本当の外の日射に一致することはまずない。
#
# それでかまわない。レシピが出す水の量は
#
#   K = need × 面積 × (センサー値 ÷ coef × film) ÷ 10
#
# であり、こちらが need を
#
#   need = 潅水量 ÷ (センサー値 ÷ RECIPE_RADIATION_COEF × film) × 10
#
# と同じ約束で作っていれば、coef が何であろうと K は狙った潅水量になる。
# 分母と分子で打ち消し合うからである。
#
# したがって、
#   ・レシピ側の 6.5 を実測に合わせて直す必要はない（直しても水は変わらない）
#   ・逆に、片方だけ直すと水がその比率でずれる。直すなら必ず両方同時
#   ・物理の透過率 COVER_TRANSMITTANCE とは無関係。連動させないこと
#
# 【デルフィ指標と比べるときだけ注意】
# デルフィの 1.5〜3 L/10MJ は「本当のハウス外日射」が基準。
# 実質日射は春に本物より約9%大きく、秋には約5%小さく出るので、
# 同じ need でも季節で実効値がずれる。春の 3.0 は本当の外日射に対しては
# 3.3 L/10MJ 相当にあたる。比較するときはこのぶんを見込むこと。
RECIPE_RADIATION_COEF = 0.65


