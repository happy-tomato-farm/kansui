# --- 9-2. 湿度は相対湿度ではなく水蒸気圧で持つ ---
#
# 【なぜ相対湿度で持ってはいけないか】
# RH = ea / es(気温) なので、RH は気温の従属変数。気温を動かせば
# 水蒸気が一切出入りしなくても RH は動く。気温と RH を別々の振幅で
# 動かすと、同じ現象を二重に数えることになる。
# 水蒸気圧 ea を状態量として持てば、VPD = es(気温) − ea で自動的に整合する。
#
# 【実測でも裏が取れている】
# ea を日中一定にして気温だけ動かすと RH の振幅は −0.372 になるが、
# 実測は −0.228 でしかない。差の 0.144 は、作物が出した水蒸気が
# ハウスにこもって RH を押し戻す分。密閉している冬ほど大きい。
#
# 【なぜ振幅をゼロにするか】
# ★実測では日中に +0.3〜0.7 kPa 上がるので、一定は物理的には正しくない。
#   にもかかわらず一定にしたほうが合う。理由は 9-3 の平滑化補正と
#   打ち消し合うため。実測257日で比べた結果:
#
#     やり方                  比の中央値  平均絶対誤差  日射別の振れ幅
#     ea振幅を月ごとに入れる      0.935     0.091 L/m²     0.057
#     ea を日中一定にする        0.965     0.063 L/m²     0.030  ★
#
#   ea振幅を入れていちばん外すのは暗い日（0〜4MJ で 0.916）。月ごとの
#   固定振幅では、蒸散の少ない日にも水蒸気がこもることにしてしまうため。
#   日射に比例させる案も試したが相関 −0.069 で成立しない
#   （ea の振幅を決めているのは蒸散量ではなく換気の開閉だった。
#    11〜2月は密閉で 0.53〜0.73、3〜6月は換気で 0.29 に揃う）。
