# --- 9-2. 湿度は相対湿度ではなく水蒸気圧で持つ ---
#
# 【なぜ相対湿度で持ってはいけないか】
# RH = ea / es(気温) なので、RH は気温の従属変数。気温を動かせば
# 水蒸気が一切出入りしなくても RH は動く。気温と RH を別々の振幅で
# 動かすと、同じ現象を二重に数えることになる。
# 水蒸気圧 ea を状態量として持てば、VPD = es(気温) − ea で自動的に整合する。
#
# 【実測でも裏が取れている】
# ea を日中一定にして気温だけ動かすと RH の振幅は −0.372 になるが、
# 実測は −0.228 でしかない。差の 0.144 は、作物が出した水蒸気が
# ハウスにこもって RH を押し戻す分。密閉している冬ほど大きい。
#
