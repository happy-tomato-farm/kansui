#  - Comparing stomatal characteristics and transpiration rates of
#    greenhouse-cultivated tomato leaves according to their vertical positions
#    https://link.springer.com/article/10.1007/s13580-025-00727-6
#  - Variation and simulation of tomato transpiration in a greenhouse
#    under different ventilation modes
#    https://www.sciencedirect.com/science/article/pii/S0378377424006176
#  - Evapotranspiration partitioning of greenhouse grown tomato using a
