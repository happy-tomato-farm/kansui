# 【ここで光合成の作り込みを止めた理由】
#
# 非直角双曲線に替えて光応答は正しく飽和するようになったが、それでも
# 葉の純光合成は文献値に届かない。原因を追ったところ、光ではなく
# **CO2 の通り道**が頭打ちを作っていることが分かった。
#
#   PPFD1500・25℃・400ppm で CO2 の総コンダクタンス gc = 0.164 mol/(m²·s)
#   Pmax を無限大にしても純光合成は 26.7 μmol/(m²·s) で止まる
#   実際の動作点（Pmax=45）では 13.6 μmol/(m²·s)
#
# しかも比較先の文献値（20〜28）はキュベット内の測定で、強制送風により
