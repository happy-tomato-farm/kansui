# 堆肥のNは有機態で、作付けの年に無機化するのは 20〜30% にすぎない。
# 残りは何年もかけてじわじわ出てくる。つまり**堆肥のNは「その作期に施した
# 肥料」ではなく「土が持っている供給力」そのもの**として振る舞う。
# 地力窒素に数えるほうが物理的に正しい。
#
# 【理由2: 記録の単位が信用できない】（ユーザー確認済み）
# 追肥管理シートの堆肥は N比 1.0・P比 21・K比 25 で、比率としてありえない。
# 投入量 2.00〜4.00 という数字も、kg なのか t なのか袋数なのか分からない。
# もし 3.48 が「トン」で堆肥のN含量が 10 kg/t なら N は 34.8 kg になり、
# シートの 3.48 kg の10倍になる。**10倍の不確かさがある量を施肥Nに
# 足し込むと、逆算の結論がその不確かさに振り回される。**
#
# 【これで何が解決するか】
# 堆肥を施肥Nから外せば、施肥Nは**信用できる記録だけ**で構成される
# （固形肥料と液肥。袋数×入数で量が決まり、成分比も表示値）。
# 堆肥の不確かさは地力窒素という「もともと逆算で決める量」に吸収され、
# 結論を壊さない。
#
# 【★この扱いが効く作期】
# 東ハウスの作期2021〜2023は、基肥が堆肥だけで固形のN肥料を入れていない。
# つまりこの3作期の基肥Nは全額が堆肥由来だった。
#   作期2021 東  基肥N 1.50 kg/10a（堆肥 2.61 のみ）
#   作期2022 東  基肥N 2.00 kg/10a（堆肥 3.48 のみ）
#   作期2023 東  基肥N 2.00 kg/10a（堆肥 3.48 のみ）
# この3作期は地力窒素の下限を決める位置にいるので、扱いを間違えると
# 結論が動く。
