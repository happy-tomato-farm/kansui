# 瞬時値の最大で絶対値を論じてはいけない。
#
# 【この節から学ぶこと】
# 合わない量を一律の係数で埋めようとしたら、まず疑うこと。
# ずれが季節や条件で向きを変えるなら、原因は複数あり、
# 一律の係数はそれを隠すだけで直さない。


