# --- 11-8. 給液ECの帯（量はNで決め、ECで挟む）---
#
# 【役割分担】
#   量を決めるのはN需要。ECはその結果が危ない側に出たときだけ効く上限と下限。
#   「ECを目標にしてN量を決める」のではない。向きが逆。
#
# 【なぜこの向きなのか（文献）】
#
#  ① 公的な施肥基準は、すべて「1日のN量」で書かれている
#     北海道立道南農業試験場「ハウストマト養液土耕マニュアル」
#       1日のN施肥量 0.075 / 0.15 / 0.30 / 0.60 kg-N/10a・日 の4段階。
#       段階は**葉柄の硝酸濃度**（NO3メーター）で診断して選ぶ。
#       定植前の土壌硝酸態窒素は 5 mg/100g 未満が基準、
#       15 以上なら窒素施肥を省略。堆肥は窒素評価量の75%を減肥。
#       → 給液ECはN量の決定に出てこない。塩類集積の話として別に書かれている。
#     https://www.hro.or.jp/upload/51777/tomato_fertigation_dounan.pdf
#
#     ★うちの作期の施肥N 48 kg-N/10a ÷ 約290日 = 0.166 kg-N/10a・日 で、
#       この表の下側の帯に乗る。堆肥と地力があるぶん低めで筋が通っている。
#
#  ② EC一定の管理は、実際に失敗の原因として報告されている
#     愛知県「夏秋トマトの給液管理の見直しによる肥料コストの削減
#             ～窒素日施用に基づいた給液の取組事例～」（2025年3月）
#       EC 1.0〜1.7 dS/m の一定管理で**草勢過多・異常茎・尻腐果**が発生。
#       1日のN量を基準に切り替えたところ、肥料 15%削減・収量 前年比+5%、
#       茎径は変化なしで草勢は安定。
#       窒素利用効率（吸収N/投入N）の実測は 80〜90%（6月中旬まで）→ 70%。
#       快晴で給液が多かった日は 67% まで低下。
#       → 第10-5節の FERTILIZER_N_EFFICIENCY = 0.70 はここに合う。
#       → 同時に「明るい日にECを固定したままN量を増やすと効率が落ちる」
#         ことの実測証拠でもある。
#     https://www.pref.aichi.jp/uploaded/attachment/558628.pdf
#
#  ③ ECを動かす目的は「N量を守ること」だと明記されている
#       「雨天日は給水量が減るため、窒素量を確保できるようECを
#         0.1〜0.2 dS/m上げて給液を行った」（同上）
#       「常に排液ECを測定し、給液ECが排液ECを下回るように調整する」（同上）
#     → N量が主、ECが従。段5で出した「排液ECを測れ」という結論と一致。
#
#  ④ ECが担っているのは量ではなく、草姿の振り方と上限
#     ・高ECは生殖方向、低ECは栄養方向に振る（crop steering）。
#       冬は日射が足りず草勢過多になりやすいので高ECで生殖側に振る。
#       → デルフィの指導はこれ。理屈として正しい。
#     ・高ECで果実の吸水が減り小玉化、一方で乾物率は直線的に上がる。
#       → 収量↓・糖度↑のトレードオフそのもの。
#     ・EC 2.3〜5.1 を超えると望ましくない減収、3.5〜9.0 で品質向上。
#       → 第11-5節のしきい値 2.5 dS/m と整合。
#     ・EC 9 dS/m では吸水が EC 1 の60%まで低下。
#     ・**強い光 × 高EC で尻腐果**が出る。
#       → 「春先はECを下げる」の根拠はN量の話ではなく、
#         尻腐果と吸水阻害。4〜6月の上限を厳しくする理由。
#     https://www.sciencedirect.com/science/article/abs/pii/S0304423800001904
#     https://www.sciencedirect.com/science/article/abs/pii/S0304423800002193
#     https://aroya.io/en/resources/crop-steering
#
# 【帯の上限をどう出したか】
# ECe（飽和抽出液のEC。文献のしきい値はこの基準）から逆算した。
#   給液EC → 根圏EC … 濃縮倍率 3 倍と置く（下の定数。★実測していない）
#   根圏EC → ECe    … soil_solution_to_saturated_extract(θfc = 0.420)
#                      比例係数 0.836
# 逆に辿ると
#   ECe 2.5 → 根圏EC 2.99 → 給液EC 1.00
#   ECe 3.0 → 根圏EC 3.59 → 給液EC 1.20
#   ECe 3.5 → 根圏EC 4.19 → 給液EC 1.40
#   ECe 4.0 → 根圏EC 4.78 → 給液EC 1.60
#
# 【月別の置き方】
#   4〜6月（強光期）… 上限 1.00（ECe 2.5 ＝ 減収ゼロのしきい値）
#                      強光×高ECで尻腐果が出るので、ここは譲らない
#   11〜1月（低日射）… 上限 1.40〜1.60（ECe 3.5〜4.0）
#                      品質向上域で、生殖側へのsteeringを意図して許す
#   9〜10月          … 上限 1.00。段5で見つけた盲点なので**上げない**。
#                      流亡がゼロで塩の出口がなく、根圏ECが年間で最高になる
#   下限 0.40        … 原水EC 0.15 より十分上。運用の最小 0.44（6月）に近い。
#                      暗い日にN量が落ちて液肥が薄くなりすぎるのを防ぐ
#
# ★★12月の運用値 1.93 はこの上限 1.60 を超えている。
#   つまりこの帯は、いまの冬の管理を少し下げる向きに効く。
#   ただし根圏ECの濃縮倍率 3 倍は実測していない推定なので、
#   **排液のECをEC計で月1回測るまでは暫定**として扱うこと。
#   実測が入れば上限はまとめて引き直せる。
