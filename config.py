# --- 9-3. なめらかな曲線で代表させたことによる目減りを戻す係数 ---
#
# 【なぜ必要か】
# 蒸散は入力に対して下に凸（convex）。VPD は気温に対して指数的に立ち上がり、
# 日射が強いほど葉温が上がってさらに VPD が開く。凸な関数では
# ギザギザを均すと必ず値が下がる（イェンセンの不等式）。
# 雲の切れ間の一瞬の強光、正午前後の気温のとがり——そこで稼いでいた水が、
# なめらかな曲線にすると消える。
#
# 【大きさを測った】
# 実測5分値を並べ、片方ずつモデルの形に差し替えて切り分けた（257日）。
#
#   全部実測（検算）          1.000  ← 手計算が真値と一致することの確認
#   日射だけ半正弦に          0.970  ← 雲のギザギザを失う分
#   気温・湿度だけモデルに      0.964  ← 日変化のとがりを失う分
#   両方                    0.938  ≒ 0.970 × 0.964
#
# 2つは独立に掛け算で効く。ea を日中一定にした過大が一部を相殺して
# 0.965 まで戻るので、残りを 1/0.965 ≒ 1.036 で埋める。
#
# ★これは原因不明の穴埋めではない。向きも大きさも説明がつく既知のバイアス。
#   予報から雲の時間分布は分からないので、形の工夫では直せない。
#   廃止した「センサー較正係数」（第4-3節）とは性質が違う。
#
# ★積算値にだけ掛ける。瞬時のピーク蒸散速度には掛けない
#   （補正の大きさを積算値で測ったため）。光合成にも同じ理屈が
#   当てはまるはずだが、そちらは検証していないので掛けていない。
