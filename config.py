DIURNAL_VAPOR_PRESSURE_AMPLITUDE_KPA = 0.0

# --- 9-3. なめらかな曲線で代表させたことによる目減りを戻す係数 ---
#
# 【なぜ必要か】
# 蒸散は入力に対して下に凸（convex）。VPD は気温に対して指数的に立ち上がり、
# 日射が強いほど葉温が上がってさらに VPD が開く。凸な関数では
# ギザギザを均すと必ず値が下がる（イェンセンの不等式）。
# 雲の切れ間の一瞬の強光、正午前後の気温のとがり——そこで稼いでいた水が、
# なめらかな曲線にすると消える。
#
# 【大きさを測った】
# 実測5分値を並べ、片方ずつモデルの形に差し替えて切り分けた（257日）。
#
#   全部実測（検算）          1.000  ← 手計算が真値と一致することの確認
#   日射だけ半正弦に          0.970  ← 雲のギザギザを失う分
#   気温・湿度だけモデルに      0.964  ← 日変化のとがりを失う分
#   両方                    0.938  ≒ 0.970 × 0.964
#
# 2つは独立に掛け算で効く。ea を日中一定にした過大が一部を相殺して
# 0.965 まで戻るので、残りを 1/0.965 ≒ 1.036 で埋める。
#
# ★これは原因不明の穴埋めではない。向きも大きさも説明がつく既知のバイアス。
#   予報から雲の時間分布は分からないので、形の工夫では直せない。
#   廃止した「センサー較正係数」（第4-3節）とは性質が違う。
#
# ★積算値にだけ掛ける。瞬時のピーク蒸散速度には掛けない
#   （補正の大きさを積算値で測ったため）。光合成にも同じ理屈が
#   当てはまるはずだが、そちらは検証していないので掛けていない。
DIURNAL_SMOOTHING_CORRECTION = 1.036

# --- 9-4. 夜の扱い ---
#
# 【何が問題だったか】
# 以前は夜も日中の振幅から外挿していた。日射ゼロの時刻は正弦の谷なので、
# 「日中平均 − 振幅 × 0.64」という値になる。これが暖房の効いた
# ハウスの夜と合わない。5月の例で
#
#   モデルの夜   19.9℃ / RH 60%  → VPD 0.945 kPa
#   実測の夜     16.6℃ / RH 80%  → VPD 0.408 kPa
#
# 2倍以上の過大。実際の夜間蒸散は1日の 3〜10% なのに、モデルでは 15% を
# 占めていた。夜を実測水準に直すと蒸散量が 13% 減る（1.021 → 0.871）。
# この過大が、9-3 の平滑化による過小と打ち消し合って、見かけ上
# 帳尻が合っていた。両方を正した上で 9-3 の係数で埋めるのが筋。
#
# 夜の気温・水蒸気圧・CO2 は core/advisor.py の調和関数で日付から出す。
# 夜の気温は作業計画シートの夜間目標（14℃→13.5℃）とほぼ一致しており、
# 暖房の設定温度そのものが出ている。
#
# 日射が平年からずれても夜の値はほとんど動かない（当てはめた傾きは
# 気温 +0.007 ℃/MJ、ea −0.005 kPa/MJ）。夜は日射と無関係なので、
# 推定式に日射の項を入れていない。
NIGHT_RADIATION_THRESHOLD_W_PER_M2 = 0.0
