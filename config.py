# 7. 土壌（生物環境物理学の基礎 第9章）
# =============================================================================
# 中央ハウスの土はシルト質壌土。pF曲線の実測値が
# 生物環境物理学/土性の調査.xlsx にある（13点）。
#
# ★★★ 単位についての重要な注意 ★★★
#
# xlsx の ψm 列は「J/kg」と表記されているが、**実際の数値は cm H2O**。
# フィットや圃場容水量の読み取りでは、必ず次の換算を通すこと。
#
#     ψ [J/kg] = 0.0980665 × h [cm H2O]
#
# 【なぜそう判断したか】
# 1. このデータは SWRC Fit（関勝寿, 東洋大）https://seki.webmasters.gr.jp/swrc/
#    で当てはめたもの。同サイトの単位の説明に
#      "Unit of pressure head is cm H2O in the sample data of UNSODA"
#      「ψ = 0.098 h」
#    とあり、標準入力は cm H2O。
# 2. 測定点を cm として読むと、標準的な測定系列にぴたりと一致する。
#      1〜160 cm   … 砂柱法（吸引法）の標準ステップ
#      345 / 690   … 1/3 bar / 2/3 bar（加圧板法）
#      2000〜15000 … 2 / 5 / 10 / 15 bar（加圧板法）
#    とくに最終点 15000 cm = 14.7 bar は永久しおれ点そのもので、
#    「しおれ点まで測って終わり」という自然な測り方になる。
#    J/kg として読むと最終点が 150 bar となり、そこまで測れる装置はない。
# 3. cm として読むと、この土の定数が文献のシルト質壌土に収まる。
#      有効水分量 0.172（文献 0.13〜0.20）／圃場容水量の空気率 8.2%
#    J/kg として読むと 0.072 と 6.3% で、どちらも範囲外になる。
#
# 【xlsx 側の pF 列は使わないこと】
