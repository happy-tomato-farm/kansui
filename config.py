#
#   期間        倍率
#   2023作期    1.01
#   2024作期    1.06
#   2025作期    1.21
#   3作期通算    1.09
#
# 日射の強さ別に見ると、実際の運用はこうなっていた。
#
#   日射[MJ]   0〜2   2〜4   4〜6   6〜9  9〜12 12〜16 16〜30
#   倍率       0.00   0.21   0.60   1.13   1.09   1.10   1.23
#
# 暗い日は止めて土の貯金を使い、明るい日に1.1〜1.2倍で補充している。
# 快晴日の 1.1〜1.23 の中ほどを採って 0.15 とした。
#
# 【★一律に掛ける値ではない】
# 暗い日にこの倍率を掛けると水が多すぎる。実際の運用では
# 日射4MJ未満は止めているので、アプリが暗い日の数字を出したときは
# 「止める」判断のほうが実態に合う（advise() が警告を出す）。
#
# 【増やしても吸えるわけではない】
# 904日を通して水収支を回すと、潅水を 2622 → 7350 L/m²（2.8倍）に
# しても、作物が吸える量は 2246 → 2290 とほぼ変わらない。
