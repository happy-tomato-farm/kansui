# --- 10-4. 地力窒素（★唯一の未知数。実績から逆算する）---
#
# 土が作期を通して供給するN量 [kg-N/10a/作]。有機物の無機化で出てくる分と、
# 作付け前に土にあった無機態Nの合計。
#
# ★土耕では測りようがない。可給態窒素の培養試験（30℃・4週間）を
#   毎年やるのは現実的でないので、**実績から逆算する**立場を採る。
#
#     地力窒素 = 吸収N需要（収量から逆算） − 施肥N × 利用率
#
# 【30.5 の出どころ】（2026-10-01・tools/N収支を検証.py で逆算）
#
# 【使ったデータ】
# 8作期 × 2ハウス = 16点のうち **13点**。東ハウスの作期2021〜2023を外した。
# この3作期は基肥Nの記録が抜けている（固形のN肥料が「東計 0」になっており、
# シート側のハウス別集計でも同じ。実際には入れている——2026-10-01 ユーザー確認）。
# 施肥Nが実際より少なく出るので、地力窒素を過大に見積もってしまう。
#
# 【解き方】
# 16点から解けるのは1本の式しかない。
#
#     地力窒素 + 施肥N × 利用率 = 吸収N需要
#
# 未知数は2つなので**組み合わせだけが決まる**。そこで2段で絞った。
#
#  (1) 硬い下限: 利用率は1を超えられない（施肥したNより多くは吸えない）。
#        地力窒素 ≧ 需要N − 施肥N
#      いちばん厳しいのは作期2024の東で 67.0 − 48.2 = 18.8 kg-N/10a。
#      ただしこの下限では利用率が 0.62〜1.00 になり、文献の 0.6〜0.8 より高い。
#      **下限は下限であって実際の値ではない。**
#
#  (2) 利用率に文献の範囲を当てる。中央ハウスの直近4作期（記録が完全で、
#      施肥水準がいまの運用に近い）の平均は 需要 64.3・施肥 48.3 なので
#
#        利用率 0.60 → 地力窒素 35.4
#        利用率 0.70 → 地力窒素 30.5   ← 既定値
#        利用率 0.80 → 地力窒素 25.7
#
# 【結論】
# 地力窒素 25.7〜35.4 kg-N/10a/作、中ほどで 30.5。下限 18.8 と矛盾しない。
# 一般的とされる範囲（施設の土で 10〜30）の上端にあたるが、この圃場は
# 8月にふすま・ねばりん・コフナなどの有機物を毎年入れているので、
# 上端に来ること自体は不自然ではない。
#
# 【★確定値ではない。確かめる道は1つ】
# **土壌診断の硝酸態N・アンモニア態Nを読むこと。**作付け前と作終わりの
# 2点で測れば、作期中に土が出した量が直接出る。土壌診断のデータは
# Notion に写真で保管してあり、1回読めば済む（毎年の測定は要らない）。
#
# 【堆肥はここに含まれる】
# 第10-3-2節のとおり、堆肥のNは施肥Nではなくこの地力窒素の側に数えている。
# 記録上の堆肥Nは作期あたり 1.2〜2.3 kg/10a だが、記録の単位が怪しいので
# 内訳としては当てにしない。30.5 という合計だけを使う。
SOIL_N_SUPPLY_KG_PER_10A = 30.5
SOIL_N_SUPPLY_PLAUSIBLE_RANGE = (10.0, 30.0)

# --- 10-5. 施肥Nの利用率 ---
#
# 施肥したNのうち、作物が吸える位置まで届く割合。
#
# 【★これは逆算で決まらない。文献から置いている】
# 上の地力窒素とこの利用率は、実績からは**別々には決まらない**。
# 解けるのは「地力窒素 + 施肥N × 利用率 = 需要N」という1本の式だけで、
# 未知数は2つある。そこで利用率を文献の目安（土耕の点滴で 0.6〜0.8）から
# 置き、その中ほどの 0.70 を既定にした。地力窒素 30.5 はその結果である。
#
#   SOIL_N_SUPPLY_KG_PER_10A = 30.5 と FERTILIZER_N_EFFICIENCY = 0.70 は
#   **セットの値**。どちらかを変えるなら両方やり直すこと。
#   0.60 なら 35.4、0.80 なら 25.7 が対になる。
#
# 【実績と矛盾しないことは確かめてある】
# 利用率は1を超えられないという制約から、地力窒素の下限は 18.8 kg/10a。
# 0.70 を採ったときの 30.5 はこれより上にあり、矛盾しない。
#
# 【★利用率は固定値ではない】
# 施肥量を増やすと下がる。地力窒素を 30.5 に固定して解くと
#   施肥 70.0（作期2020）→ 0.45 ／ 施肥 47.7（作期2024）→ 0.73
# と、施肥を減らしたほうが効率がよい。実績のN効率（果実kg ÷ 施肥N kg）が
# 429 → 663 へ上がったのと同じ現象で、**多く入れた年は増やした分が
# 吸われずに抜けていた**ということだ。
# 0.70 は「いまの施肥水準（約48 kg-N/10a）での値」であって、
# 施肥量を大きく変えるなら当てはまらない。
#
# 【★二重計上に注意】
# 流亡（潅水で根圏の外へ押し出される分）を別に引き算する設計にするなら、
# この利用率に流亡を含めてはいけない。どちらの経路で数えるかを決めて、
# 決めたほうだけを使うこと。
#
#   設計A（この節の既定）… 利用率にすべて込める。流亡は別に引かない
#   設計B（第11節で実装予定）… 根圏のN収支を回して流亡を明示的に出す。
#                              そのときの利用率は 0.9 前後まで上げる
#
# 「合わない量を一律の係数で埋める」のは第4-3節の 1.20 と同じ失敗の型だ。
# 設計Bへ進むときは、この値を必ず見直すこと。
FERTILIZER_N_EFFICIENCY = 0.70
FERTILIZER_N_EFFICIENCY_SENSITIVITY = (0.60, 0.70, 0.80)


# =============================================================================
# 11. 塩類濃度（EC）— デルフィの指導を数字で確かめるために
# =============================================================================
# 【この節がある理由】（2026-10-01 ユーザー聞き取り）
# 施肥の時期配分は、N栄養の都合で決めたものではない。デルフィのコーチから
#
#     「冬は窒素を多めに流して EC を上げる、春先は EC を下げる」
#
# という指導を受けてこの運用になっている。つまり**狙っているのは EC**で、
# Nはその手段として動いている。したがって第10節（N需要）だけでは
# 妥当性を判断できない。ECが効く経路を別に入れる必要がある。
#
# 【ECが効く3つの経路】
#
#  (1) 浸透ポテンシャル → 吸水を抑える
#      土壌溶液に塩が溶けていると、根が水を引くのに余分な力が要る。
#      これは乾いた土から吸うのと同じ効きかたをする。
#
#  (2) 果実の品質 → 糖度が上がる
#      果実への水の流入が減るので、同じ糖が薄まらずに濃くなる。
#      高EC栽培で糖度が上がるのはこの機序。
#
#  (3) 収量 → 下がる
#      (1) の裏側。水が入らなければ果実は大きくならない。
#
# **(2) と (3) は同じ現象の表と裏**で、どちらを取るかという選択になる。
# 冬は光が足りず果実が水っぽくなりやすいので (2) を取り、
# 春は蒸散要求が大きいので (1) を避けて (3) を取る——これが指導の中身だと
# 読める。このモデルで数字にして確かめる。

# --- 11-1. EC から浸透ポテンシャルへ ---
#
# 【換算】
#     浸透圧 π [bar] ≒ 0.36 × EC [dS/m]
#     1 bar = 100 kPa ≒ 100 J/kg（水の密度 1000 kg/m³ だから）
#   よって
#     |浸透ポテンシャル| [J/kg] ≒ 36 × EC [dS/m]
#
# 【★これがマトリックポテンシャルより一桁大きい】
# core/soil.py の soil_to_leaf_driving_force にすでに書いてあるとおり。
#
#     圃場容水量（pF 1.8）のマトリックポテンシャル  6.2 J/kg
#     土壌溶液 EC 2.0 dS/m の浸透ポテンシャル      72   J/kg  ← 12倍
#
# つまり**十分に湿った土では、根が感じる水ポテンシャルはECで決まる**。
# 第9章の式9.20・9.22 は含水率だけで吸水を決めているので、
# ECを入れないと春の吸水不足を説明しきれない。
# （README「実際の潅水量とどう違うか」で「5〜6月は土は湿っているのに
#   吸水が届かない（Aw 1.00 なのにストレス46%）」と出ていたのがこれ。）
OSMOTIC_POTENTIAL_J_PER_KG_PER_DS_PER_M = 36.0

# --- 11-2. ECの3つの基準（★混同しないこと）---
#
# ECは「どれだけ水で薄めて測ったか」で値が変わる。3つが出てくる。
#
#   (a) EC(1:5)      土1に水5を加えて測る。**日本の土壌診断の標準**。
#                    土壌診断_一覧.xlsx の EC はこれ。
#   (b) 土壌溶液EC    現地の含水率のままの溶液の濃度。
#                    **根が実際に感じるのはこれ**。浸透ポテンシャルの元。
#   (c) ECe（飽和抽出） 飽和まで水を入れたペーストから測る。
#                    **文献の塩害しきい値はこの基準**（FAOなど）。
#
# 【換算】水で薄めた倍率の比で換算する（塩が全部溶けていると仮定）。
#
#     重量含水率 [g/g] = 体積含水率 θ ÷ 土の仮比重 ρb
#
#     土壌溶液EC = EC(1:5) × 5 ÷ 現地の重量含水率
#     ECe        = EC(1:5) × 5 ÷ 飽和の重量含水率
#
# ★この線形換算は近似。石膏などの溶けきらない塩があると過大になる。
#   この土はCECが42 meと高く腐植も10%以上あるので、交換性の塩基が
#   1:5抽出で余分に出てくる可能性がある（＝土壌溶液ECを過大に見積もる向き）。
#
# 【★土の仮比重は実測していない】
# 腐植10%以上・推定CEC 42 me という土壌診断の値からすると、
# 黒ボク寄りの軽い土で 0.8〜1.0 g/cm³ と見るのが妥当。中央を採る。
# この値は換算倍率にそのまま効くので、感度を見ること。
SOIL_BULK_DENSITY_G_PER_CM3 = 0.9
SOIL_BULK_DENSITY_SENSITIVITY = (0.8, 0.9, 1.0)

#: EC(1:5) の水/土の重量比。日本の土壌診断の標準。
